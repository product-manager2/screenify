import type { Config } from './config.js';
import type { Capture, Manifest } from './manifest.js';
import type { Plan } from './plan.js';
import type { LibraryStatus } from './status.js';
import type { Store } from './store.js';

function flags(c: Capture, staleIds: Set<string>, config: Config): string {
  const f: string[] = [];
  if (staleIds.has(c.id)) f.push('STALE');
  if (c.dirty) f.push('dirty tree');
  if (config.defaultBranch && c.branch && c.branch !== config.defaultBranch) f.push(`branch ${c.branch}`);
  return f.join(', ');
}

function short(commit: string | null): string {
  return commit ? commit.slice(0, 8) : '—';
}

/**
 * Renders INDEX.md: one page listing every feature with its screens and flows, their paths,
 * capture commit and flags (stale, dirty tree, off the default branch), then pending plan items.
 */
export function renderIndex(store: Store, manifest: Manifest, plan: Plan, status: LibraryStatus, config: Config): string {
  const captures = Object.values(manifest.captures);
  const staleIds = new Set(status.stale.map((s) => s.capture.id));
  const out: string[] = [];
  out.push(`# App screenshots: ${store.repoName}`, '');
  out.push(
    'Generated by Screenify. Paths are relative to this folder. Every image has a `.md` sidecar with the same name',
    '(front matter: route, source files, commit; body: visible text and accessibility outline), so `grep -r "Button label" screens flows`',
    'finds the right image without opening any. Flow boards show the steps of one action; full-resolution frames sit in `<flow>--frames/`.',
    '',
  );
  out.push(
    `Updated ${new Date().toISOString()} · ${captures.filter((c) => c.kind === 'screen').length} screens · ${captures.filter((c) => c.kind === 'flow').length} flows · ${status.stale.length} stale · ${status.pending.length} not yet captured`,
    '',
  );
  if (status.stale.length) out.push('Refresh stale captures with `screenify refresh`.', '');

  const byFeature = new Map<string, Capture[]>();
  for (const c of captures) {
    const k = `${c.platform}/${c.feature}`;
    byFeature.set(k, [...(byFeature.get(k) ?? []), c]);
  }
  for (const key of [...byFeature.keys()].sort()) {
    const list = byFeature.get(key)!;
    out.push(`## ${key}`, '');
    const screens = list.filter((c) => c.kind === 'screen').sort((a, b) => a.id.localeCompare(b.id));
    if (screens.length) {
      out.push('| Screen | State | Viewport | Theme | Image | Commit | Flags |', '| --- | --- | --- | --- | --- | --- | --- |');
      for (const c of screens) {
        out.push(`| ${c.name} | ${c.state} | ${c.viewport} | ${c.theme} | \`${c.image}\` | ${short(c.commit)} | ${flags(c, staleIds, config)} |`);
      }
      out.push('');
    }
    const flows = list.filter((c) => c.kind === 'flow').sort((a, b) => a.id.localeCompare(b.id));
    if (flows.length) {
      out.push('| Flow | Viewport | Theme | Board | Frames | Commit | Flags |', '| --- | --- | --- | --- | --- | --- | --- |');
      for (const c of flows) {
        const boards = (c.boards ?? [c.image]).map((b) => `\`${b}\``).join('<br>');
        out.push(`| ${c.name} | ${c.viewport} | ${c.theme} | ${boards} | ${c.frames?.length ?? 0} | ${short(c.commit)} | ${flags(c, staleIds, config)} |`);
      }
      out.push('');
    }
  }
  if (!captures.length) {
    out.push(
      plan.items.length
        ? '_No captures yet. The plan is ready: write recipes for its items and `screenify run` them._'
        : '_No captures yet. Ask your agent to use the screenify skill: an agent reads the code and writes the plan (`screenify discover` prints its brief), then capture follows._',
      '',
    );
  }

  if (status.pending.length) {
    out.push('## Not yet captured', '');
    for (const i of status.pending) {
      const where = i.example ?? i.route;
      const what = i.kind === 'screen' ? `states: ${i.states.map((s) => s.name).join(', ')}` : `${i.steps.length} steps${i.writes ? ', writes data' : ''}`;
      out.push(`- \`${i.id}\`${where ? ` (${where})` : ''}, ${what}${i.note ? `. ${i.note}` : ''}`);
    }
    out.push('');
  }
  if (status.skipped.length) {
    out.push('## Skipped', '');
    for (const i of status.skipped) out.push(`- \`${i.id}\`${i.note ? `: ${i.note}` : ''}`);
    out.push('');
  }
  if (plan.items.length) {
    out.push(
      `_Plan: ${plan.items.length} items written by the discovery agent${plan.commit ? ` at commit ${short(plan.commit)}` : ''} (\`plan.json\`). Staleness follows each item's \`sources\`: the files that shape that screen or flow._`,
      '',
    );
  }
  return out.join('\n');
}
